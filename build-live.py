#!/usr/bin/env python3
"""Build the read-only public site in live/ from the editable local index.html."""
from pathlib import Path
import json
import shutil

root = Path(__file__).resolve().parent
live = root / "live"

html = (root / "index.html").read_text()

remove = [
    '    <button class="tool-btn" id="btn-edit" title="Edit plugin details and screenshots">Edit shelf</button>\n',
    '    <button class="tool-btn" id="btn-sync" title="Push latest edits to GitHub">Sync to GitHub</button>\n',
]
for snippet in remove:
    if snippet not in html:
        raise SystemExit(f"build-live.py: expected markup not found: {snippet[:70]!r}")
    html = html.replace(snippet, "")

# The published build must not carry internal LAN/Tailscale addresses.
private_shot = 'images:[{src:"assets/omarchy-server-kill_preview.png",caption:"Server Kill panel: grouped servers, ports, URLs and Kill buttons"}],'
if private_shot not in html:
    raise SystemExit("build-live.py: Server Kill screenshot reference not found")
html = html.replace(private_shot, "images:[],")

# The GW2 settings capture shows an API key field; leave it out of the public build.
key_shot = ',{src:"assets/shaun.gw2-trading-post_preview-settings.jpg",caption:"API key settings panel"}'
if key_shot not in html:
    raise SystemExit("build-live.py: GW2 settings screenshot reference not found")
html = html.replace(key_shot, "")

marker = "<title>Plug Shelf · Shaun Gordon</title>"
html = html.replace(
    marker,
    marker + "\n<!-- Read-only public build generated by build-live.py. Do not hand-edit. -->",
    1,
)

live.mkdir(exist_ok=True)
(live / "index.html").write_text(html)

for name in ("DESIGN.md", "README.md"):
    shutil.copy2(root / name, live / name)

# Published edits: keep Shaun's new screenshots except ones with a key field
# or the wrong subject. Those stay local only.
edits = json.loads((root / "edits.json").read_text())
hidden = 0
for slug, override in edits.items():
    keep = []
    for image in override.get("images", []):
        caption = image.get("caption", "")
        if "API key settings" in caption or "not a plugin panel" in caption:
            hidden += 1
        else:
            keep.append(image)
    override["images"] = keep
(live / "edits.json").write_text(json.dumps(edits, indent=2) + "\n")

assets_out = live / "assets"
if assets_out.exists():
    shutil.rmtree(assets_out)
assets_out.mkdir()
copied = []
for src in sorted((root / "assets").iterdir()):
    if not src.is_file() or src.name.startswith("omarchy-server-kill_preview") or src.name == "shaun.gw2-trading-post_preview-settings.jpg":
        continue
    shutil.copy2(src, assets_out / src.name)
    copied.append(src.name)

print(f"Built {live / 'index.html'}")
print(f"Copied {len(copied)} screenshots; omitted Server Kill captures")
print(f"Omitted {hidden} edited screenshots with private or off-topic content")
print("Edit shelf and Sync controls removed")
